// usage: node tools/build-tajweed-test-data.js
// Copies the rule → example words (with surah/ayah) from quran/tajweed/index.html into quran/tajweed/test/examples.js,
// so Quranic text in the test always comes from the verified Mushaf-based examples, never hand-typed.
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const s = fs.readFileSync(path.join(ROOT, 'quran/tajweed/index.html'), 'utf8');
const ex = {};
for (const m of s.matchAll(/<div class="h-card"[^>]*><div[^>]*>([^<]+)<\/div>([\s\S]*?)(?=<div class="h-card"|<\/details>|$)/g)) {
  const rule = m[1].trim();
  for (const e of m[2].matchAll(/data-s="(\d+)" data-a="(\d+)"[\s\S]*?<strong[^>]*>([^<]+)<\/strong>/g)) {
    ex[rule] = ex[rule] || [];
    if (!ex[rule].some(x => x.w === e[3])) ex[rule].push({ w: e[3], s: +e[1], a: +e[2] });
  }
}
const dir = path.join(ROOT, 'quran/tajweed/test');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'examples.js'), '// Generated by tools/build-tajweed-test-data.js from quran/tajweed/index.html — do not edit by hand.\nwindow.TJ_EX = ' + JSON.stringify(ex) + ';\n');
console.log(Object.keys(ex).length, 'rules,', Object.values(ex).reduce((n, a) => n + a.length, 0), 'examples');
