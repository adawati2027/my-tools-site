// usage: node tools/build-admission-data.js [saved-admhec-pages.html...]
// Builds jo/students/what-can-i-study/data.js from bachelor-guide's BACHELOR_PROGRAMS,
// attaching 2021–2025 competitive-minimum history from owner-saved admhec.gov.jo pages (matched by dropdown code + major name).
// Private minimums are raised to the national per-field floor (قرار مجلس التعليم العالي 2024/268) when a listed value is lower.
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(ROOT, 'jo/students/bachelor-guide/index.html'), 'utf8');
const a = src.indexOf('const BACHELOR_PROGRAMS = ['), b = src.indexOf('\n];', a);
const P = new Function('return ' + src.slice(src.indexOf('[', a), b + 2))();
const CODES = { '100': 'الجامعة الأردنية', '200': 'جامعة اليرموك', '300': 'جامعة مؤتة', '400': 'جامعة العلوم والتكنولوجيا الأردنية', '500': 'الجامعة الهاشمية', '600': 'جامعة آل البيت', '700': 'جامعة البلقاء التطبيقية', '800': 'جامعة الحسين بن طلال', '900': 'جامعة الطفيلة التقنية', '1000': 'جامعة العلوم الإسلامية العالمية' };
const strip = s => s.replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
const hist = {}; let years = null;
for (const f of process.argv.slice(2)) {
  const h = fs.readFileSync(f, 'utf8');
  const code = [...h.matchAll(/selected="selected" value="(\d+)"/g)].map(m => m[1]).find(c => CODES[c]);
  if (!code) continue;
  const rows = [...h.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)].map(m => [...m[1].matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/g)].map(c => strip(c[1]))).filter(r => r.length > 2);
  years = rows[0].slice(1).map(Number);
  for (const r of rows.slice(1)) hist[CODES[code] + '|' + r[0]] = r.slice(1).map(v => { const n = parseFloat(v); return isNaN(n) ? null : n; });
}
const norm = s => s.replace(/[أإآ]/g, 'ا');
function floor(spec) {
  const s = norm(spec);
  if (/(^|\s|ال)طب(\s|$)|اسنان|طب و|طب ال/.test(s) && !/بيطري|مخبري|مختبر|اشع|تخدير|طبيعي|طبيه|طبية/.test(s)) return 85;
  if (/هندس|عمار|صيدل/.test(s) && !/برمجيات/.test(s)) return 80;
  if (/شريع|فقه|اصول الدين/.test(s)) return 75;
  if (/تمريض|قبال|مختبر|مخبري|اشع|تخدير|علاج|سمع|نطق|بصريات|تغذي|اسعاف|صحه|صحة/.test(s)) return 70;
  if (/قانون|حقوق/.test(s)) return 65;
  return 60;
}
const out = [];
let withHist = 0, raised = 0;
for (const p of P) {
  const gov = p.universityType === 'حكومية';
  let m = gov ? p.minAvgCompetitive : (p.minAvgSingle != null ? p.minAvgSingle : p.minAvgCompetitive);
  if (m == null) continue;
  const e = { u: p.university, gv: gov ? 1 : 0, c: p.city, s: p.specialization, g: p.specGroup, m };
  if (!gov) { const fl = floor(p.specialization); if (m < fl) { e.m = fl; e.fl = 1; raised++; } }
  if (gov) { const hh = hist[p.university + '|' + p.specialization]; if (hh) { e.h = hh; withHist++; } }
  if (p.tuitionPerHour != null) { e.tph = p.tuitionPerHour; if (p.creditHours) e.ch = p.creditHours; if (p.intlCurrency) e.cur = p.intlCurrency; }
  out.push(e);
}
const js = '// Generated by tools/build-admission-data.js — do not edit by hand.\nwindow.ADM_YEARS = ' + JSON.stringify(years || [2021, 2022, 2023, 2024, 2025]) + ';\nwindow.ADM_DATA = ' + JSON.stringify(out) + ';\n';
const dir = path.join(ROOT, 'jo/students/what-can-i-study');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'data.js'), js);
console.log('entries', out.length, '| gov', out.filter(e => e.gv).length, '| with 5y history', withHist, '| private raised to national floor', raised, '| bytes', js.length);
